"""Regenerate index.md from page frontmatter.

Deterministic: the agent edits frontmatter, never index.md.
Usage: python bin/wiki-index.py
"""
from __future__ import annotations

from wikilib import PAGE_TYPES, ROOT, load_pages

HEADINGS = {"source": "Sources", "entity": "Entities", "concept": "Concepts", "query": "Queries"}


def main() -> None:
    pages = load_pages()
    out = ["# Index", "", "Generated by `python bin/wiki-index.py`. Edit page frontmatter, not this file.", ""]
    for kind in PAGE_TYPES:
        group = sorted(
            (p for p in pages if p.meta.get("type") == kind),
            key=lambda p: str(p.meta.get("title", p.slug)),
        )
        out.append(f"## {HEADINGS[kind]} ({len(group)})")
        out.append("")
        for p in group:
            # Source pages show the source's own date: the agent ranks sources by it when claims disagree.
            stamp = f"dated {p.meta.get('dated', '')}" if kind == "source" else str(p.meta.get("updated", ""))
            out.append(f"- [[{p.slug}]] — {p.meta.get('summary', '')} `{stamp}`")
        out.append("")
    (ROOT / "index.md").write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
    print(f"index.md: {len(pages)} pages")


if __name__ == "__main__":
    main()
